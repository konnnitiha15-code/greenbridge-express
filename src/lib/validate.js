const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

// 文字列が UUID 形式かどうか
function isUuid(v) {
  return typeof v === 'string' && UUID_RE.test(v)
}

module.exports = { isUuid }
